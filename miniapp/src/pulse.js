// Пульс экрана: как часто перезапрашивать состояние и как называть его возраст.
//
// До этого экран грузился один раз при входе и больше никогда: строка
// «41 сек назад» через пять минут врала, а обмен так и оставался «неизвестно»,
// пока человек не нажмёт кнопку. Число, которое человек сверяет с роутером,
// обязано жить само -- иначе приложение показывает прошлое, выдавая его за
// настоящее.
import { pluralRu } from './labels.js'

// Агент отчитывается примерно раз в двадцать секунд, поэтому чаще десяти
// спрашивать бессмысленно: свежее его последнего отчёта данных всё равно нет.
export const PULSE_MS = 10000

// Опрашивается только открытый экран конкретного роутера: Telegram держит
// мини-апп живым дольше, чем человек на него смотрит.
export function shouldPulse(state) {
  return Boolean(state?.visible && state?.routerID != null)
}

// Порог, после которого показания перестают быть «сейчас». Час -- это уже не
// «чуть-чуть отстало», а другая эпоха: за это время VPN-туннель успевает упасть и
// подняться дважды.
const STALE_AFTER_SEC = 3600

export function freshnessLabel(ageSec) {
  if (ageSec == null) return 'роутер ещё не отчитывался'
  if (ageSec >= STALE_AFTER_SEC) return 'данные устарели — роутер давно молчит'
  if (ageSec < 60) {
    return `проверено ${ageSec} ${pluralRu(ageSec, 'секунду', 'секунды', 'секунд')} назад`
  }
  const min = Math.floor(ageSec / 60)
  return `проверено ${min} ${pluralRu(min, 'минуту', 'минуты', 'минут')} назад`
}
