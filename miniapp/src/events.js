// Лента: группировка по дням. Всё, что было тут раньше -- фильтры и
// вычисление длительности по паре событий -- удалено вместе с причиной их
// существования. Длительность теперь считает бэкенд: он один видит неделю,
// а клиенту приезжали только пятьсот новейших строк, то есть полтора часа,
// и посчитанная по ним длительность была догадкой под видом факта.
//
// Функция осталась для режима «как есть», где строки по-прежнему сырые.
export function groupByDay(events = []) {
  const byDay = new Map()
  for (const e of events) {
    const day = (e.ts ?? '').slice(0, 10)
    if (!byDay.has(day)) byDay.set(day, [])
    byDay.get(day).push(e)
  }
  return [...byDay.entries()]
    .sort((a, b) => (a[0] < b[0] ? 1 : -1))
    .map(([day, items]) => ({ day, events: items }))
}
