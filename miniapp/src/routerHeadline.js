// Шапка главного экрана: одна строка состояния и один вывод под ней.
//
// Во главе -- работа туннелей. Службы роутера (DNS, панель, агент) объясняют
// картину, но не они её задают: человек открывает приложение, чтобы узнать,
// идёт ли трафик, а не какая из пяти проверок моргнула.
//
// Порядок веток здесь -- это порядок важности новостей, и он не случайный.
// Молчащий роутер перебивает всё: в этот момент любое другое показание на
// экране -- вчерашнее, и выдать его за текущее было бы той самой ложью,
// против которой написана половина этого приложения.
import { humanAge, incidentCopy, pluralRu } from './labels.js'

export function routerHeadline({ router, traffic, incidents = [], tunnels = [] } = {}) {
  const age = router?.last_seen_age_sec
  // Молчащий роутер делает УСТАРЕВШИМИ все показания на экране, а не только
  // шапку: число поднятых линий, адрес выхода, состояние служб -- всё это
  // данные на момент последнего отчёта, и показать их как текущие значит
  // соврать. Отличается от cold: холодной шапка бывает и у живого роутера с
  // тревогой, а его показания как раз свежие.
  const stale = router?.status === 'offline' || router?.status === 'sleeping'

  // Роутер, который ещё ни разу не выходил на связь. Это не авария (чинить
  // нечего) и не норма -- отдельное состояние со своими словами.
  if (age == null && (router?.status === 'offline' || router?.status === 'sleeping')) {
    return {
      tone: 'off',
      cold: true,
      stale,
      tag: 'роутер ещё ни разу не отвечал',
      verdict: 'Агент установлен, но ни одного отчёта от него не приходило.',
    }
  }

  if (router?.status === 'offline' || router?.status === 'sleeping') {
    return {
      tone: 'danger',
      cold: true,
      stale,
      tag: `роутер не отвечает · ${humanAge(age)}`,
      verdict: `Последний отчёт ${humanAge(age)} назад. Всё, что показано ниже, — данные на тот момент, а не сейчас.`,
    }
  }

  // Живой роутер с открытой тревогой: называем поломку, а не её номер.
  // Первая тревога в списке -- та, которую бэкенд счёл главной.
  if (incidents.length > 0) {
    const name = incidents[0].check_name
    // У линии человеческого имени нет: «awg12» -- идентификатор, который
    // человек нигде не видел. В шапке называем ПОСЛЕДСТВИЕ, а сам туннель и
    // его имя остаются в карточке тревоги, где их сверяет тот, кто чинит.
    if (name.startsWith('tunnel_')) {
      // Упавшая линия -- ещё не потерянный обход. Пока жива другая, трафик
      // идёт через неё, и кричать «не открывается» значит гнать человека
      // чинить то, что у него работает. Тревога остаётся -- линию поднимать
      // надо, — но заголовок обязан говорить правду о последствиях.
      const alive = tunnels.find(
        (t) => t.run_state === 'running' && `tunnel_${t.tunnel_id}` !== name,
      )
      if (alive) {
        return {
          tone: 'warn',
          cold: true,
          stale,
          tag: 'работает на запасной линии',
          verdict: `Одна линия упала, обход идёт через «${alive.name || alive.tunnel_id}». Починить упавшую всё равно стоит: запасная осталась одна.`,
        }
      }
      return {
        tone: 'danger',
        cold: true,
        stale,
        tag: 'заблокированное не открывается',
        verdict: 'Линия обхода не отвечает. Банки, госуслуги и остальной интернет работают как обычно.',
      }
    }
    const copy = incidentCopy(name)
    return {
      tone: 'danger',
      cold: true,
      stale,
      tag: copy.what.toLowerCase(),
      verdict: copy.why || 'Подробности — в карточке тревоги ниже.',
    }
  }

  if (traffic?.mode === 'vpn') {
    const via = traffic.egress_tunnel_name || traffic.egress_tunnel_id
    return {
      tone: 'sig',
      cold: false,
      stale,
      tag: 'всё работает',
      // Единого ответа «весь трафик идёт через X» не существует: внутри
      // всегда умная маршрутизация. Заблокированное идёт через туннель,
      // российское и незаблокированное -- напрямую. Обещать общий маршрут
      // значит врать человеку о том, как устроен его собственный интернет.
      verdict: `Заблокированное открывается через «${via}». Остальное идёт напрямую, как обычно.`,
    }
  }

  // Не авария, но и не норма: обход блокировок сейчас не действует, и сказать
  // это надо словом, а не отсутствием слова.
  if (traffic?.mode === 'direct') {
    return {
      tone: 'warn',
      cold: true,
      stale,
      tag: 'трафик идёт напрямую',
      verdict: 'Ни одна линия не несёт основной маршрут: трафик уходит напрямую через провайдера, и обход блокировок не работает.',
    }
  }

  if (traffic?.mode === 'singbox') {
    return {
      tone: 'sig',
      cold: false,
      stale,
      // Имя движка маршрутизации человеку не нужно: он спрашивает «работает
      // ли», а не «чем именно считается маршрут». Суть та же, что и в обычном
      // режиме -- заблокированное через туннель, остальное напрямую, — только
      // выбор идёт для каждого адреса, и единой линии выхода нет.
      tag: 'всё работает',
      verdict: 'Заблокированное открывается через линию обхода, остальное идёт напрямую. Маршрут выбирается для каждого адреса отдельно.',
    }
  }

  return {
    tone: 'off',
    cold: false,
    stale,
    tag: age != null ? `роутер на связи · ответ ${humanAge(age)} назад` : 'роутер на связи',
    verdict: 'Роутер не сообщил, какая линия основная. Соберите отчёт заново.',
  }
}

// Сколько линий поднято из настроенных. Живёт рядом с шапкой, а не внутри
// разметки: это счёт со склонением, то есть логика, и проверять её в вёрстке
// было бы нечем. Ноль линий -- «0 линий», а не «0 линии»: в приложении, где
// человек сверяет показания с роутером, сломанное склонение читается как
// сломанные данные.
export function linesSummary(live, total) {
  if (!total) return 'Туннелей нет'
  return `${live} ${pluralRu(live, 'линия', 'линии', 'линий')} из ${total}`
}
