// Шапка главного экрана: одна строка состояния и один вывод под ней.
//
// Во главе -- работа туннелей. Службы роутера (DNS, панель, агент) объясняют
// картину, но не они её задают: человек открывает приложение, чтобы узнать,
// идёт ли трафик, а не какая из пяти проверок моргнула.
//
// Порядок веток здесь -- это порядок важности новостей, и он не случайный.
// Молчащий роутер перебивает всё: в этот момент любое другое показание на
// экране -- вчерашнее, и выдать его за текущее было бы той самой ложью,
// против которой написана половина этого приложения.
import { humanAge, incidentCopy } from './labels.js'
import { carrierKnown, isAlive, reserveIDs } from './trafficPath.js'

export function routerHeadline({ router, traffic, incidents = [], tunnels = [] } = {}) {
  const age = router?.last_seen_age_sec
  // Молчащий роутер делает УСТАРЕВШИМИ все показания на экране, а не только
  // шапку: число поднятых VPN-туннелей, адрес выхода, состояние служб -- всё это
  // данные на момент последнего отчёта, и показать их как текущие значит
  // соврать. Отличается от cold: холодной шапка бывает и у живого роутера с
  // тревогой, а его показания как раз свежие.
  const stale = router?.status === 'offline' || router?.status === 'sleeping'

  // Роутер, который ещё ни разу не выходил на связь. Это не авария (чинить
  // нечего) и не норма -- отдельное состояние со своими словами.
  if (age == null && (router?.status === 'offline' || router?.status === 'sleeping')) {
    return {
      tone: 'off',
      cold: true,
      stale,
      tag: 'роутер ещё ни разу не отвечал',
      verdict: 'Агент установлен, но ни одного отчёта от него не приходило.',
    }
  }

  if (router?.status === 'offline' || router?.status === 'sleeping') {
    return {
      tone: 'danger',
      cold: true,
      stale,
      tag: `роутер не отвечает · ${humanAge(age)}`,
      verdict: `Последний отчёт ${humanAge(age)} назад. Всё, что показано ниже, — данные на тот момент, а не сейчас.`,
    }
  }

  // Живой роутер с открытой тревогой: называем поломку, а не её номер.
  // Первая тревога в списке -- та, которую бэкенд счёл главной.
  if (incidents.length > 0) {
    const name = incidents[0].check_name
    // У туннеля из тревоги человеческого имени нет: «awg12» -- идентификатор, который
    // человек нигде не видел. В шапке называем ПОСЛЕДСТВИЕ, а сам туннель и
    // его имя остаются в карточке тревоги, где их сверяет тот, кто чинит.
    if (name.startsWith('tunnel_')) {
      const lineName = (t) => t?.name || t?.tunnel_id
      // Несущего назвал сам роутер (агент v0.41+): схема и заголовок обязаны
      // говорить про ОДИН и тот же туннель. 18.09 workrouter: обход шёл через
      // живой hipvps, а заголовок писал «работает на запасном» -- угадывал.
      if (carrierKnown({ traffic, tunnels })) {
        const carrier = tunnels.find((t) => t.tunnel_id === traffic.egress_tunnel_id)
        const via = traffic.egress_tunnel_name || lineName(carrier)
        if (isAlive(carrier, incidents)) {
          const dead = tunnels.find((t) => `tunnel_${t.tunnel_id}` === name)
          const deadName = lineName(dead) || name.slice('tunnel_'.length)
          const reserves =
            reserveIDs({ traffic, tunnels }) ??
            tunnels.filter((t) => t !== carrier && isAlive(t, incidents)).map((t) => t.tunnel_id)
          if (reserves.length === 0) {
            return {
              tone: 'warn',
              cold: true,
              stale,
              tag: 'всё работает, резерва нет',
              verdict: `Обход идёт через «${via}». Запасной «${deadName}» не отвечает — если основной ляжет, подхватить некому.`,
            }
          }
          return {
            tone: 'warn',
            cold: true,
            stale,
            tag: 'всё работает, один запасной упал',
            verdict: `Обход идёт через «${via}». Запасной «${deadName}» не отвечает, другой запасной наготове.`,
          }
        }
        // Несущий мёртв: трафик обхода идёт в него, пока правила его не сменят.
      } else {
        // Упавший VPN-туннель -- ещё не потерянный обход. Пока жив другой, трафик
        // идёт через него, и кричать «не открывается» значит гнать человека
        // чинить то, что у него работает. Тревога остаётся -- VPN-туннель поднимать
        // надо, — но заголовок обязан говорить правду о последствиях.
        const alive = tunnels.find((t) => isAlive(t, incidents) && `tunnel_${t.tunnel_id}` !== name)
        if (alive) {
          // При раздельной маршрутизации несущего выбирают правила, и роутер
          // старше v0.41 его не называет: назвать живой туннель -- угадать.
          const verdict =
            traffic?.mode === 'split'
              ? 'Один VPN-туннель упал, обход идёт через оставшиеся. Починить упавший всё равно стоит: запаса стало меньше.'
              : `Один VPN-туннель упал, обход идёт через «${lineName(alive)}». Починить упавший всё равно стоит: запасной остался один.`
          return {
            tone: 'warn',
            cold: true,
            stale,
            tag: 'работает на запасном VPN-туннеле',
            verdict,
          }
        }
      }
      return {
        tone: 'danger',
        cold: true,
        stale,
        tag: 'заблокированное не открывается',
        verdict: 'VPN-туннель обхода не отвечает. Банки, госуслуги и остальной интернет работают как обычно.',
      }
    }
    const copy = incidentCopy(name)
    return {
      tone: 'danger',
      cold: true,
      stale,
      // Только первая буква: целиком в нижний регистр ушло бы и «VPN».
      tag: copy.what.charAt(0).toLowerCase() + copy.what.slice(1),
      verdict: copy.why || 'Подробности — в карточке тревоги ниже.',
    }
  }

  if (traffic?.mode === 'vpn') {
    const via = traffic.egress_tunnel_name || traffic.egress_tunnel_id
    return {
      tone: 'sig',
      cold: false,
      stale,
      tag: 'всё работает',
      // Единого ответа «весь трафик идёт через X» не существует: внутри
      // всегда умная маршрутизация. Заблокированное идёт через туннель,
      // российское и незаблокированное -- напрямую. Обещать общий маршрут
      // значит врать человеку о том, как устроен его собственный интернет.
      verdict: `Заблокированное открывается через «${via}». Остальное идёт напрямую, как обычно.`,
    }
  }

  // Главный выход напрямую, а заблокированное уводят правила -- обычная
  // раздельная маршрутизация, а не поломка. Имя VPN-туннеля бэкенд даёт, только
  // когда живой один: при нескольких выбирают правила, и назвать любой --
  // угадать.
  if (traffic?.mode === 'split') {
    const via = traffic.egress_tunnel_name || traffic.egress_tunnel_id
    return {
      tone: 'sig',
      cold: false,
      stale,
      tag: 'всё работает',
      verdict: via
        ? `Заблокированное открывается через «${via}». Остальное идёт напрямую, как обычно.`
        : 'Заблокированное открывается через VPN-туннели обхода, какой взять — решают правила. Остальное идёт напрямую, как обычно.',
    }
  }

  // Не авария, но и не норма: обход блокировок сейчас не действует, и сказать
  // это надо словом, а не отсутствием слова.
  if (traffic?.mode === 'direct') {
    return {
      tone: 'warn',
      cold: true,
      stale,
      tag: 'трафик идёт напрямую',
      verdict: 'Ни одно правило не ведёт в работающий VPN-туннель: всё идёт напрямую через провайдера, и заблокированное не откроется.',
    }
  }

  if (traffic?.mode === 'singbox') {
    return {
      tone: 'sig',
      cold: false,
      stale,
      // Имя движка маршрутизации человеку не нужно: он спрашивает «работает
      // ли», а не «чем именно считается маршрут». Суть та же, что и в обычном
      // режиме -- заблокированное через туннель, остальное напрямую, — только
      // выбор идёт для каждого адреса, и единого VPN-туннеля выхода нет.
      tag: 'всё работает',
      verdict: 'Заблокированное открывается через VPN-туннель обхода, остальное идёт напрямую. Маршрут выбирается для каждого адреса отдельно.',
    }
  }

  return {
    tone: 'off',
    cold: false,
    stale,
    tag: age != null ? `роутер на связи · ответ ${humanAge(age)} назад` : 'роутер на связи',
    // Правила не прочитались (список перерос то, что агент читает): туннель
    // роутер назвал, а повтор проверки упрётся в тот же список -- звать
    // «соберите заново» значит гонять человека по кругу.
    verdict: traffic?.reason === 'rules_unreadable'
      ? 'Правила обхода не удалось прочитать целиком, поэтому по ним сейчас не понять, что идёт через VPN.'
      : 'Роутер не сообщил, какой VPN-туннель основной. Соберите отчёт заново.',
  }
}
