// Палитра приложения. Единственный источник истины по цвету.
//
// Тема одна — тёмная, и это решение, а не упрощение: приложение открывают
// ночью и в машине, где светящийся белый экран мешает. Раньше цвета брались
// из themeParams Telegram, потом появилась своя пара светлая/тёмная; теперь
// от Telegram не берётся ничего, кроме факта, что он есть.
//
// Имена токенов — из дизайн-системы проекта Claude Design (её же перечисляет
// _adherence.oxlintrc.json), чтобы макет и код звали один цвет одинаково.
// Прежние имена (--page, --surface, --text, --muted, --accent, --border)
// объявлены в style.css псевдонимами: экраны переезжают на новые не разом.
//
// Числа контраста проверяет test/theme.test.js — менять цвет, не прогнав
// тест, нельзя. Замеры на 2026-08-19: --ink 15.7:1 на --surf, --dim 6.4:1,
// --sig 13.6:1, самый скромный запас у --bad на --surf2 — 5.7:1.
export const PALETTE = {
  bg: '#0c1013',
  surf: '#141a1f',
  surf2: '#1b2229',
  ink: '#eef3f5',
  dim: '#8f9ea8',
  line: 'rgba(255,255,255,0.09)',
  line2: 'rgba(255,255,255,0.05)',
  // Сигнальный лайм значит «линия жива» и обозначает действие. Красить им
  // заголовки и плашки просто за красоту нельзя — он перестанет что-либо
  // значить ровно в тот момент, когда встретится дважды на одном экране.
  sig: '#c8f24a',
  ok: '#5fd08a',
  warn: '#ffbf3d',
  bad: '#ff6a58',
  // Погашенный светодиод на корпусе и текст на заливке лаймом. Это не тема,
  // а физика прибора и производное от --sig соответственно.
  ledOff: '#39424a',
  onSig: '#0d1204',
}

export function cssVarName(key) {
  return '--' + key.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())
}

// Пишет палитру в документ. Схема больше не параметр: тема одна, и выбирать
// нечего. root передаётся, чтобы тест мог подсунуть заглушку вместо document.
export function applyPalette(root = document.documentElement) {
  for (const [key, value] of Object.entries(PALETTE)) {
    root.style.setProperty(cssVarName(key), value)
  }
  root.setAttribute('data-theme', 'dark')
  return PALETTE
}
