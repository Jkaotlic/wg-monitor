import { quoteParts } from '../text.js'

// Имя в «ёлочках» -- VPN-туннель, роутер, сайт, правило. Держит его вместе
// вёрстка (.q: inline-block), а не символ: дефис в имени остаётся настоящим,
// и скопированное из приложения совпадёт с тем, что на роутере. Хук склейки
// (text.js) внутрь .q не заходит.
export function Q({ children }) {
  return <span class="q">«{children}»</span>
}

// Готовая строка с именами внутри -- заголовки ответов, тексты шитов. Её
// собирают чистые функции (routeLookup, labels, экраны для шита), а имена в
// ней экран кладёт в <Q>. Фрагмент, а не массив: строки между именами --
// дети фрагмента, и термин в них хук склейки по-прежнему видит.
export function Quoted({ text }) {
  // Не строка (JSX, число, пусто) -- показывается как есть: резать нечего.
  if (typeof text !== 'string') return text ?? null
  return <>{quoteParts(text).map((p, i) => (typeof p === 'string' ? p : <Q key={i}>{p.q}</Q>))}</>
}
