import { describe, it, expect } from 'vitest'
import { antennaSlots, antennaOverflow, ANT_MAX } from '../src/components/RouterDevice.jsx'

// Антенна -- это туннель. Не «шесть слотов, из них три пустые»: пустой слот
// обещает ёмкость, которой у роутера нет, и врёт про его устройство.
// Крайние случаи здесь названы явно, потому что именно на них рисунок
// перестаёт быть показанием.
describe('antennaSlots', () => {
  it('штырей ровно столько, сколько туннелей', () => {
    expect(antennaSlots(3)).toHaveLength(3)
    expect(antennaSlots(5)).toHaveLength(5)
  })

  // Одинокий туннель стоит прямо по центру, а не жмётся к краю корпуса:
  // роутер с одной линией -- это нормальный роутер, а не полупустой.
  it('одинокая антенна стоит по центру', () => {
    const [only] = antennaSlots(1)
    expect(only.t).toBe(0)
  })

  it('крайние антенны симметричны относительно центра корпуса', () => {
    const s = antennaSlots(4)
    expect(s[0].t).toBe(-1)
    expect(s[3].t).toBe(1)
    // 174 -- центральная линия корпуса; веер обязан быть симметричным,
    // иначе прибор выглядит собранным криво, а не показывающим состояние.
    expect(s[0].baseX + s[3].baseX).toBe(2 * 174)
  })

  // Роутер без туннелей -- реальное состояние: только что заведённый. Рисовать
  // на нём антенны было бы выдумкой.
  it('без туннелей штырей нет вовсе', () => {
    expect(antennaSlots(0)).toEqual([])
    expect(antennaOverflow(0)).toBe(0)
  })

  // Больше восьми штырей на 390 px -- расчёска: имена под ними не читаются,
  // и картинка из показания превращается в инвентарь, которым и так служит
  // список ниже. Остаток называется числом, а не рисуется.
  it('сверх предела рисуется не больше ANT_MAX, остаток считается', () => {
    expect(antennaSlots(12)).toHaveLength(ANT_MAX)
    expect(antennaOverflow(12)).toBe(12 - ANT_MAX)
  })

  it('до предела остатка нет', () => {
    expect(antennaOverflow(ANT_MAX)).toBe(0)
  })
})
