package tg

// HelpForScreen returns the inline-help body for a given panel screen.
// Used by the "ℹ Помощь" button: tap → EditMessageText replaces the
// panel body with this text; "« Назад" returns to the panel.
func HelpForScreen(screen string) string {
	switch screen {
	case "maint":
		return `🛠 Обслуживание — справка

🔁 Перезапустить hrneo — перезапустить HydraRoute-Neo (DNS/routing маршрутизатор). Безопасно; пакеты задерживаются на ~5с.
🔁 Перезапустить awg-manager — перезапустить менеджер AmneziaWG. Туннели не падают (системные), но awg-manager API недоступен ~10с.
🔁 Перезагрузить роутер — полная перезагрузка. ~2–3 мин downtime. Используется кулдаун 5 мин.
📦 Прошивка — установить новую версию KeeneticOS. Включает reboot. Кулдаун 5 мин.
🔄 Проверить апдейты — заново снять отчёт о доступных версиях.`
	case "routes":
		return `🛣 Маршруты — справка

Снимок DNS- и Static-маршрутов HydraRoute-Neo, сгруппированный по туннелям.
🔄 Перенести правила — массово переключить все правила одного туннеля на другой. WAN/system правила НЕ трогаются.
🔁 Обновить — заново снять снимок.`
	case "tunnels":
		return `🎛 Туннели — справка

Снимок состояния всех туннелей: ✅ работает, 🔴 не на связи, ⏸ выключен.
▶/⏸ — включить/выключить конкретный туннель.
🔁 Перезагрузить awg-mgr — рестарт менеджера.
🔄 Обновить — заново снять снимок.`
	case "access":
		return `👥 Доступ — справка

Управление операторами роутеров. У каждого роутера есть владелец и список дополнительных Telegram-пользователей, которым можно жать кнопки именно этого роутера.
➕ Добавить оператора — перешли сообщение от человека в личку боту или напиши его числовой Telegram ID.
✖ — удалить владельца или оператора.`
	case "diag":
		return `📊 Диагностика — справка

Короткий отчёт о системе: версия awg-manager, состояние WAN, туннели, DNS.
Запуск ~30–60с. Не меняет состояние, только читает.
📄 Полный отчёт — сырые данные для отладки.
🔁 Перезапустить — снять отчёт заново.`
	case "status":
		return `📊 Статус — справка

Публикует smart-reply (📊 Что происходит?) в топик каждого роутера. Полезно, когда нужно одним тапом получить срез по всем роутерам.`
	case "doctor":
		return `🩺 Проверка — что это

Проверка запускается агентом прямо на выбранном роутере и ничего не меняет. Это важно, когда ноутбук не в домашней LAN или есть конфликт подсетей: бот смотрит состояние изнутри роутера.

Что проверяет:
  ✅ awg-manager API и версию
  ✅ активный движок: NativeWG / Kernel / HydraRoute-Neo
  ✅ управляемые туннели и маршрут по умолчанию
  ✅ PingCheck и статусы жив/не на связи
  ✅ процессы wg-monitor и awg-manager
  ✅ маршрут по умолчанию роутера

Команда ничего не меняет: не рестартит сервисы, не трогает маршруты и не включает/выключает туннели.

В админской панели кнопка «🩺 Все роутеры» ставит такую же безопасную проверку в очередь по всем роутерным топикам.`
	case "pingcheck":
		return `📡 PingCheck — что это
PingCheck — это сторожевой механизм awg-manager. Раз в N секунд он пингует целевой
хост через туннель; при N подряд провалах awg-mgr автоматически
рестартит туннель.

Что показывает панель:
  🟢 — туннель жив, последний ping успешен
  🔴 — пинги провалены, туннель не на связи
  ⏸ — проверка для туннеля выключена оператором
  ❓ — состояние неизвестно

Колонки:
  82ms  — задержка последнего ping
  ✓417  — счётчик успешных проверок (с момента старта механизма)
  ✗0/3  — счётчик провалов / порог рестарта
  restart×0 — сколько раз механизм рестартил туннель

Кнопки:
  [⏸/▶ awgN] — выключить/включить проверку конкретного туннеля
  [▶ Проверить сейчас] — запустить проверку вручную
  [🔄 Обновить] — перечитать состояние

Параметры (host / interval / threshold) задаются NDMS-профилем
ping-check на роутере; меняются через ndmc, не из бота.`
	}
	return "ℹ Помощь по этому экрану ещё не написана."
}

// HelpRowFor returns a single-row inline-keyboard suffix containing the
// "ℹ Помощь" button for a given panel screen. Designed to be appended
// to existing panel keyboards just before the "✖ Закрыть" row.
func HelpRowFor(screen string) []InlineKeyboardButton {
	return []InlineKeyboardButton{
		{Text: "ℹ Помощь", CallbackData: "panel:0:help:" + screen},
	}
}
