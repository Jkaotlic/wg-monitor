package tg

// HelpForScreen returns the inline-help body for a given panel screen.
// The text is split by screen so every message stays below Telegram limits.
func HelpForScreen(screen string) string {
	switch screen {
	case "operator":
		return `ℹ Operator guide

Главное правило: работай в топике нужного роутера. Кнопки там уже привязаны к этому роутеру.

Как читать статусы:
  ✅ ok - работает
  🟡 warning - есть подозрение, лучше проверить
  🔴 hard - подтверждённый сбой
  📵 offline - агент давно не присылал heartbeat

Как работают кнопки:
  • большинство действий ставится в command queue роутера
  • результат придёт отдельным сообщением в этот же топик
  • не жми одну и ту же кнопку много раз подряд, пока нет результата или явной ошибки
  • проверки и doctor ничего не меняют; рестарты, импорт .conf, маршруты и обновления меняют состояние

Где что искать:
  📊 Статус - быстрый ответ "что происходит"
  🩺 Проверка - безопасный doctor изнутри роутера
  🎛 Туннели - включить/выключить и увидеть handshake
  🛣 Маршруты - DNS/Static правила и перенос между туннелями
  🛠 Обслуживание - версии, рестарты, прошивка, opkg
  📡 PingCheck - сторожевой ping и авто-рестарт туннеля
  Amnezia Premium / HideMy.name - ключи, коды, выгрузка .conf и импорт

Флот:
  self_update и массовые проверки запускает только админ. Успех обновления считается по heartbeat с новой версией, а не по самому факту нажатия.

Подробности: help:premium, help:tunnels, help:routes, help:maint, help:pingcheck.`
	case "premium":
		return `ℹ Premium cabinets

Amnezia Premium:
  • пришли vpn:// ключ прямо в топик роутера
  • бот проверит логин, сохранит key только за этим топиком и удалит сообщение с secret
  • можно хранить несколько ключей, открывать разные и удалять лишние
  • "Выгрузить .conf" открывает страны; выбор страны скачивает config и отправляет .conf в топик
  • если country config уже выпускался, бот выгрузит его повторно; перевыпуска ключа нет

HideMy.name:
  • пришли цифровой access code в топик роутера
  • бот проверит serverlist, сохранит code за топиком и удалит сообщение с secret
  • можно хранить несколько кодов
  • в списке серверов выбирай нужную страну/сервер
  • бот скачивает именно AmneziaWG 2.0 .conf

После выгрузки:
  • .conf отправляется документом в топик
  • импорт туннеля ставится в command queue роутера
  • результат импорта придёт отдельным сообщением
  • если ответа долго нет, сначала жми 🩺 Проверка, а не повторяй импорт несколько раз

Безопасность:
  • secrets не показываются в справке и не нужны в логах
  • ключи/коды хранятся отдельно от state.db в закрытых JSON-файлах
  • оператор видит только топики, куда его добавили`
	case "alerts":
		return `ℹ Алерты

✅ Зелёный - восстановилось или всё работает.
🟡 Жёлтый - первая проблема. Обычно стоит подождать следующую проверку или нажать 🩺 Проверка.
🔴 Красный - устойчивый сбой. Тут уже можно смотреть историю, запускать doctor, PingCheck или рестарт конкретного туннеля.
📵 Offline - агент не присылает heartbeat. Сначала проверь роутер и связь, потом обновления.

Кнопки под HARD-алертом:
  ⏸ Тише - временно приглушить именно этот check
  ✅ Понял - отметить, что алерт увидели
  🔇 Тихо до утра - не будить ночью
  📋 История - последние события по check
  🔁 Перезапуск туннеля - меняет состояние
  📊 Диагностика / ▶ Тест связи - безопасные проверки`
	case "fleet":
		return `ℹ Флот и обновления

Массовые действия доступны админу в /panel:
  🔎 Аудит всех - собрать версии и состояние
  ⬆ Обновить все - поставить текущую backend version через self_update
  🩺 Все роутеры - поставить doctor по всем топикам
  🪄 Оживить топики - отправить приветствие/клавиатуру в существующие топики

Важно:
  • команда уходит в queue каждого роутера отдельно
  • старые агенты без безопасного self_update пропускаются
  • успех обновления подтверждается heartbeat с новой версией
  • повторный деплой не засоряет память сам по себе; deferred задачи заменяются актуальными, а временные файлы используются только на время установки`
	case "mobile":
		return `ℹ Мобильные роутеры

Экран показывает мобильные агенты отдельно от стационарных:
  • last seen - когда был последний heartbeat
  • version - какая версия агента на устройстве
  • ring / pending - канал обновлений и ожидаемая версия

Если мобильный давно offline:
  1. не запускай массовые обновления вслепую
  2. проверь последний heartbeat и версию
  3. дождись выхода устройства в сеть или попроси владельца открыть приложение/сеть`
	case "maint":
		return `🛠 Обслуживание

Что безопасно:
  🔄 Проверить апдейты - только читает доступные версии
  🩺 Проверка - читает состояние изнутри роутера

Что меняет состояние:
  🔁 Перезапустить hrneo - короткая пауза DNS/routing, обычно несколько секунд
  🔁 Перезапустить awg-manager - API недоступен около 10 секунд, системные туннели не должны падать
  🔁 Перезагрузить роутер - downtime около 2-3 минут, есть cooldown
  📦 Прошивка - ставит KeeneticOS и включает reboot
  ⬆ opkg upgrade - обновляет Entware-пакеты

После нажатия жди результат из command queue. Если результата нет, сначала открой 🩺 Проверка.`
	case "routes":
		return `🛣 Маршруты

Экран показывает DNS/Static правила NDMS и HydraRoute-Neo, сгруппированные по туннелям.

Можно:
  • посмотреть, какие домены/сети идут через какой туннель
  • перенести правила одного туннеля на другой
  • добавить DNS/Static правило через мастер
  • удалить выбранное правило
  • снять снапшот маршрутов

Осторожно:
  • DNS/Static из WAN/system можно переносить отдельной кнопкой; preview покажет, что именно уйдёт
  • перенос меняет routing для всех правил выбранного туннеля
  • после изменения дождись результата и обнови экран`
	case "tunnels":
		return `🎛 Туннели

Статусы:
  ✅ работает
  🔴 нет связи
  ⏸ выключен
  ❓ нет свежих данных

Кнопки:
  ▶/⏸ - включить или выключить конкретный туннель
  🔁 awg-mgr - перезапустить менеджер
  🔄 Обновить - перечитать последний снимок

Handshake не всегда равен интернету: если handshake свежий, но сайты не открываются, запускай PingCheck или проверку маршрутов.`
	case "access":
		return `👥 Доступ

Доступ настраивает админ. У каждого роутера есть владелец и список операторов.

Оператор может работать только в топиках, куда его добавили:
  • смотреть статус
  • запускать безопасные проверки
  • управлять туннелями и маршрутами
  • пользоваться Premium-кабинетами этого топика

Команды флота, привязка топиков и управление доступами остаются только у админа.`
	case "diag":
		return `📊 Диагностика

Диагностика ничего не меняет. Она читает:
  • awg-manager API и версию
  • WAN и default route
  • туннели и handshake
  • DNS и PingCheck
  • процессы wg-monitor / awg-manager

Полный отчёт нужен для отладки. Если короткая сводка непонятна, открой сырой JSON и смотри failing tests.`
	case "status":
		return `📊 Статус

"Что происходит?" публикует smart-reply в топик роутера:
  • краткий вывод по состоянию
  • что упало
  • какой следующий шаг безопаснее

Это чтение, без изменений на роутере. Хорошая первая кнопка перед рестартами и импортами.`
	case "doctor":
		return `🩺 Проверка

Doctor запускается агентом прямо на выбранном роутере и ничего не меняет.

Проверяет:
  ✅ awg-manager API и версию
  ✅ активный движок NativeWG / Kernel / HydraRoute-Neo
  ✅ туннели, маршруты и default route
  ✅ PingCheck и статусы жив/не на связи
  ✅ процессы wg-monitor и awg-manager

Используй doctor перед рестартом, после импорта .conf и когда локальный ноутбук не видит роутер из-за маршрутов.`
	case "pingcheck":
		return `📡 PingCheck

PingCheck - сторожевой ping awg-manager. Он периодически пингует host через туннель; после нескольких подряд провалов awg-mgr может автоматически рестартить туннель.

Статусы:
  🟢 последний ping успешен
  🔴 ping провален
  ⏸ проверка выключена
  ❓ данных нет

Колонки:
  82ms - задержка последнего ping
  ✓417 - успешные проверки
  ✕0/3 - провалы / порог рестарта
  restart×0 - сколько раз механизм рестартил туннель

Кнопки:
  ⏸/▶ awgN - выключить/включить watchdog для туннеля
  ▶ Проверить сейчас - ручная проверка
  🔄 Обновить - перечитать состояние`
	}
	return "ℹ Помощь по этому экрану ещё не написана."
}

// HelpRowFor returns a single-row inline-keyboard suffix containing the
// help button for a given panel screen.
func HelpRowFor(screen string) []InlineKeyboardButton {
	return []InlineKeyboardButton{
		{Text: "ℹ Помощь", CallbackData: "panel:0:help:" + screen},
	}
}
