package callbacks

import (
	"strings"
	"testing"
)

// «Диагностика» не запускает проверку заново: агент берёт у роутера последний
// готовый отчёт, а проверяет с нуля, только если отчёта ещё нет. Обещать
// «каждый VPN-туннель на секунду перезапустится» при каждом нажатии значило
// пугать владельца тем, чего не будет, и выдавать старый отчёт за новый.
func TestDiagNowSentTextTellsItIsTheLastReport(t *testing.T) {
	s := formatQueuedStatus("diag_now", "")
	if !strings.Contains(s, "последний отчёт") {
		t.Fatalf("владелец должен знать, что придёт последний отчёт роутера: %q", s)
	}
	// Перезапуск VPN-туннелей бывает, только когда отчёта нет, -- и сказать
	// о нём можно лишь с этим условием.
	if strings.Contains(s, "перезапустится") && !strings.Contains(s, "если отчёта ещё нет") {
		t.Fatalf("перезапуск обещан без условия: %q", s)
	}
}
