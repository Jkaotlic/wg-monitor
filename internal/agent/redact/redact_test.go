package redact

import "testing"

func TestText(t *testing.T) {
	cases := map[string]string{
		"peer 198.51.100.7:51820 up":     "peer 198.*.*.7:51820 up",
		"resolve vpn.example.com failed": "resolve v***.com failed",
		"addr 2001:db8::1 set":           "addr <IPv6> set",
		"fe80:0:0:0:1:2:3:4":             "<IPv6>",
		"at 15:04:05 ok":                 "at 15:04:05 ok",
		"уже замаскировано 12*****.1":    "уже замаскировано 12*****.1",
		"": "",
		// Fix round 1: \b в Go/RE2 считает словом только [0-9A-Za-z_], и
		// адрес, приклеенный к такому символу вплотную (без пробела),
		// раньше проходил немаскированным -- граница теперь проверяется
		// вручную по соседним рунам, а не через \b.
		"peer_198.51.100.7:51820": "peer_198.*.*.7:51820",
		"x198.51.100.7":           "x198.*.*.7",
		// Кириллический хост: старые классы [a-zA-Z0-9] не видели не-ASCII
		// букв вовсе, поэтому «сайт.рф» не маскировался. Теперь классы
		// Unicode-aware (\p{L}).
		"сайт.рф failed": "с***.рф failed",
		// Версия -- три числа через точку, не четыре октета, и последняя
		// группа не буквы: ни IPv4-паттерн (нужно ровно 4 октета), ни
		// host-паттерн (TLD должен быть буквами) её не видят -- строка
		// проходит насквозь без изменений.
		"agent 2.19.9 up": "agent 2.19.9 up",
	}
	for in, want := range cases {
		if got := Text(in); got != want {
			t.Errorf("Text(%q) = %q, want %q", in, got, want)
		}
	}
}
